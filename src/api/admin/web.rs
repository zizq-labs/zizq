//! The admin web UI, served from the admin listener.
//!
//! The UI is plain HTML, CSS and JavaScript in `web/`, which talks to the
//! same `/events` WebSocket as `zizq top`. `build.rs` gzips each file at
//! compile time, so the binary carries only the compressed bytes, and they
//! are sent as they are with `Content-Encoding: gzip`. A client that does
//! not accept gzip, which no browser is, gets them decompressed instead.

use std::io::Read;

use axum::Router;
use axum::http::{HeaderMap, HeaderValue, StatusCode, header};
use axum::response::{IntoResponse, Response};
use axum::routing::get;
use flate2::read::GzDecoder;

/// A file from `web/`, as generated by `build.rs`.
struct Asset {
    path: &'static str,
    content_type: &'static str,
    etag: &'static str,
    gzipped: &'static [u8],
}

include!(concat!(env!("OUT_DIR"), "/web_assets.rs"));

/// Routes serving every asset, `index.html` at `/` and the rest by name.
pub fn routes<S>() -> Router<S>
where
    S: Clone + Send + Sync + 'static,
{
    ASSETS.iter().fold(Router::new(), |router, asset| {
        router.route(
            asset.path,
            get(move |headers: HeaderMap| async move { serve(asset, &headers) }),
        )
    })
}

fn serve(asset: &'static Asset, headers: &HeaderMap) -> Response {
    // `no-cache` still lets the browser keep a copy, but has it check the
    // ETag first, so a server upgrade takes effect on the next load.
    let common = [
        (header::CONTENT_TYPE, asset.content_type),
        (header::ETAG, asset.etag),
        (header::CACHE_CONTROL, "no-cache"),
        (header::VARY, "accept-encoding"),
    ];

    if matches_etag(headers, asset.etag) {
        return (StatusCode::NOT_MODIFIED, common).into_response();
    }

    if accepts_gzip(headers) {
        return (common, [(header::CONTENT_ENCODING, "gzip")], asset.gzipped).into_response();
    }

    let mut body = Vec::new();
    match GzDecoder::new(asset.gzipped).read_to_end(&mut body) {
        Ok(_) => (common, body).into_response(),
        Err(e) => {
            tracing::error!(%e, path = asset.path, "admin web: failed to decompress asset");
            StatusCode::INTERNAL_SERVER_ERROR.into_response()
        }
    }
}

fn header_values<'a>(
    headers: &'a HeaderMap,
    name: header::HeaderName,
) -> impl Iterator<Item = &'a str> {
    headers
        .get_all(name)
        .iter()
        .filter_map(|v: &HeaderValue| v.to_str().ok())
        .flat_map(|v| v.split(','))
        .map(str::trim)
}

fn matches_etag(headers: &HeaderMap, etag: &str) -> bool {
    header_values(headers, header::IF_NONE_MATCH).any(|tag| tag == etag || tag == "*")
}

/// Whether `Accept-Encoding` lists gzip, without ruling it out by `q=0`.
fn accepts_gzip(headers: &HeaderMap) -> bool {
    header_values(headers, header::ACCEPT_ENCODING).any(|coding| {
        let mut parts = coding.split(';').map(str::trim);
        let name = parts.next().unwrap_or("");
        let refused = parts.any(|param| {
            param
                .strip_prefix("q=")
                .and_then(|q| q.parse::<f32>().ok())
                .is_some_and(|q| q == 0.0)
        });
        name.eq_ignore_ascii_case("gzip") && !refused
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    use axum::body::{Body, to_bytes};
    use axum::http::Request;
    use tower::ServiceExt;

    const INDEX_HTML: &str = include_str!("../../../web/index.html");

    async fn get_asset(path: &str, headers: &[(&str, &str)]) -> Response {
        let mut req = Request::get(path);
        for (name, value) in headers {
            req = req.header(*name, *value);
        }
        routes::<()>()
            .oneshot(req.body(Body::empty()).unwrap())
            .await
            .unwrap()
    }

    async fn body_text(res: Response) -> String {
        let bytes = to_bytes(res.into_body(), usize::MAX).await.unwrap();
        String::from_utf8(bytes.to_vec()).unwrap()
    }

    fn gunzip(bytes: &[u8]) -> String {
        let mut text = String::new();
        GzDecoder::new(bytes).read_to_string(&mut text).unwrap();
        text
    }

    #[tokio::test]
    async fn index_is_served_gzipped_at_the_root() {
        let res = get_asset("/", &[("accept-encoding", "gzip, deflate, br")]).await;

        assert_eq!(res.status(), 200);
        assert_eq!(res.headers()["content-type"], "text/html; charset=utf-8");
        assert_eq!(res.headers()["content-encoding"], "gzip");
        assert_eq!(res.headers()["vary"], "accept-encoding");

        let bytes = to_bytes(res.into_body(), usize::MAX).await.unwrap();
        assert_eq!(gunzip(&bytes), INDEX_HTML);
    }

    #[tokio::test]
    async fn assets_referenced_by_the_index_are_served() {
        let index = body_text(get_asset("/", &[]).await).await;

        for (path, content_type) in [
            ("/app.js", "text/javascript; charset=utf-8"),
            ("/app.css", "text/css; charset=utf-8"),
        ] {
            assert!(
                index.contains(&format!("\"{}\"", &path[1..])),
                "index.html does not reference {path}"
            );
            let res = get_asset(path, &[("accept-encoding", "gzip")]).await;
            assert_eq!(res.status(), 200, "{path}");
            assert_eq!(res.headers()["content-type"], content_type, "{path}");
        }
    }

    #[tokio::test]
    async fn clients_without_gzip_get_the_asset_decompressed() {
        let res = get_asset("/", &[]).await;

        assert_eq!(res.status(), 200);
        assert!(res.headers().get("content-encoding").is_none());
        assert_eq!(body_text(res).await, INDEX_HTML);
    }

    #[tokio::test]
    async fn gzip_refused_with_q_zero_is_not_used() {
        let res = get_asset("/", &[("accept-encoding", "gzip;q=0, identity")]).await;

        assert!(res.headers().get("content-encoding").is_none());
    }

    #[tokio::test]
    async fn a_matching_etag_is_not_modified() {
        let etag = get_asset("/app.js", &[]).await.headers()["etag"].clone();

        let res = get_asset("/app.js", &[("if-none-match", etag.to_str().unwrap())]).await;

        assert_eq!(res.status(), 304);
        assert!(body_text(res).await.is_empty());
    }

    #[tokio::test]
    async fn a_stale_etag_gets_the_asset() {
        let res = get_asset("/app.js", &[("if-none-match", "W/\"0000000000000000\"")]).await;

        assert_eq!(res.status(), 200);
    }

    #[test]
    fn accepts_gzip_parses_accept_encoding() {
        let accepts = |value: &str| {
            let mut headers = HeaderMap::new();
            headers.insert(header::ACCEPT_ENCODING, value.parse().unwrap());
            accepts_gzip(&headers)
        };

        assert!(accepts("gzip"));
        assert!(accepts("br, GZIP;q=0.5"));
        assert!(!accepts("br, deflate"));
        assert!(!accepts("gzip; q=0"));
        assert!(!accepts("x-gzip-ish"));
    }
}
