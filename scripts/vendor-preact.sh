#!/usr/bin/env bash

# Regenerate web/preact.js, the copy of Preact and htm the admin web UI
# is built with.
#
# Usage:
#   ./scripts/vendor-preact.sh
#
# The web UI has no JavaScript build step: browsers load its ES modules
# directly. Preact, its hooks and htm are bundled here, once, into a
# single module exporting everything from `preact` and `preact/hooks`,
# plus `html`, htm bound to Preact's `h`. Needs Node.js and network
# access, but only when the versions below change.
#
# After changing a version, update THIRD_PARTY_LICENSES to match. A test
# checks that every package named by an `@license` line in web/ appears
# there.

set -euo pipefail

PREACT_VERSION=11.2.0
HTM_VERSION=3.1.1
ESBUILD_VERSION=0.28.2

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
OUT="${SCRIPT_DIR}/../web/preact.js"

WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT
cd "$WORK_DIR"

echo '{ "private": true }' > package.json
npm install --no-audit --no-fund --silent \
    "preact@${PREACT_VERSION}" \
    "htm@${HTM_VERSION}" \
    "esbuild@${ESBUILD_VERSION}"

cat > entry.js <<'EOF'
import { h } from "preact";
import htm from "htm";

export * from "preact";
export * from "preact/hooks";
export const html = htm.bind(h);
EOF

npx esbuild entry.js \
    --bundle \
    --format=esm \
    --minify \
    --legal-comments=none \
    --outfile=bundle.js

{
    cat <<EOF
/*!
 * Preact and htm, bundled into one ES module for the admin web UI.
 * Generated by scripts/vendor-preact.sh. Do not edit by hand.
 *
 * @license preact ${PREACT_VERSION} MIT, Copyright (c) 2015-present Jason Miller
 * @license htm ${HTM_VERSION} Apache-2.0, Copyright 2018 Google Inc.
 *
 * Full licence texts are in THIRD_PARTY_LICENSES.
 */
EOF
    cat bundle.js
} > "$OUT"

echo "Wrote ${OUT} ($(wc -c < "$OUT") bytes)"
